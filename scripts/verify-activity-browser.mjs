import assert from 'node:assert/strict';
import fs from 'node:fs';
import puppeteer from 'puppeteer-core';
import { createClient } from '@supabase/supabase-js';

process.loadEnvFile('.env.local');
process.loadEnvFile('.env.server.local');
const service = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const account = JSON.parse(fs.readFileSync('.demo-accounts.local', 'utf8')).find(a => a.role === 'admin');
const title = `verify-activity-browser-${Date.now()}`;
const base = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:3000';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const checked = r => { if (r.error) throw new Error(r.error.message); return r.data; };
const setInput = (selector, value) => page.$eval(selector, (el, value) => {
  Object.getOwnPropertyDescriptor(el instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(el, value);
  el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true }));
}, value);
const clickText = async text => {
  const handle = await page.waitForFunction(text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text && !b.disabled), {}, text);
  await handle.asElement().click();
};
const choose = async (label, option) => {
  const button = await page.waitForFunction(label => [...document.querySelectorAll('button')].find(b => b.getAttribute('aria-labelledby')?.split(' ').some(id => document.getElementById(id)?.textContent === label)), {}, label);
  await button.asElement().click();
  const item = await page.waitForFunction(option => [...document.querySelectorAll('[role="option"]')].find(b=>b.textContent.trim()===option), {}, option);
  await item.asElement().click();
};
try {
  await page.setViewport({width:1366,height:950});
  await page.goto(`${base}/#/login`,{waitUntil:'networkidle0'});
  await page.waitForSelector('#landing-login-identifier');
  await page.type('#landing-login-identifier',account.username);
  await page.type('#landing-login-password',account.password);
  await page.$eval('#landing-login-password',el=>el.closest('form').requestSubmit());
  await page.waitForFunction(()=>location.hash!=='#/login' && document.querySelector('main'),{timeout:40000});
  await page.goto(`${base}/#/ssg/events/create?kind=flag_ceremony`,{waitUntil:'networkidle0'});
  await page.waitForSelector('#event-title');
  await page.evaluate(()=>[...document.querySelectorAll('label')].find(l=>l.textContent.trim()==='Use Philippine standard ceremony week').querySelector('input').click());
  await choose('Flag ceremony type','Flag retreat / lowering');
  assert.equal(await page.$eval('input[id^="time-in-"]',el=>el.value),'16:30');
  assert.equal(await page.evaluate(()=>[...document.querySelectorAll('label')].find(l=>l.textContent.trim()==='Friday').querySelector('input').checked),true);
  fs.mkdirSync('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/flag-standard-desktop.png'});
  await choose('Activity type','Sanction / Cleaning Service');
  assert.equal(await page.$eval('main h1',el=>el.textContent),'Create Service Activity');
  const date = offset=>new Date(Date.now()+8*3600000+offset*86400000).toISOString().slice(0,10);
  await setInput('#event-title',title); await setInput('#event-details','Browser service verification');
  await setInput('#event-start-date',date(1)); await setInput('#event-end-date',date(3));
  await setInput('input[id^="time-in-"]','08:00'); await setInput('input[id^="time-out-"]','10:00');
  await clickText('Add Attendance Window');
  const ids=await page.$$eval('input[id^="time-in-"]',els=>els.map(el=>el.id));
  await setInput(`[id="${ids[1]}"]`,'13:00'); await setInput(`[id="${ids[1].replace('time-in-','time-out-')}"]`,'15:00');
  await page.evaluate(()=>[...document.querySelectorAll('label')].find(l=>l.textContent.trim()==='Save excess service hours as earned merit').querySelector('input').click());
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/service-activity-desktop.png'});
  await page.setViewport({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('main').getBoundingClientRect().left<1);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/service-activity-mobile.png'});
  await page.setViewport({width:1366,height:950});
  await clickText('Schedule Service');
  await page.waitForFunction(()=>location.hash==='#/ssg/events',{timeout:30000});
  let row=checked(await service.from('rmc_events').select('id,data').eq('data->>title',title).single());
  assert.equal(row.data.kind,'service'); assert.equal(row.data.service.overflow,'merit');
  assert.equal(row.data.attendanceWindows.length,2); assert.equal(row.data.endDate,date(3));
  await page.goto(`${base}/#/ssg/events/${row.id}/edit`,{waitUntil:'networkidle0'});
  await page.waitForSelector('#event-title');
  await setInput('label:has(input[type="date"]) input:not([id])',date(5));
  await clickText('Extend service days');
  await page.waitForFunction(()=>location.hash==='#/ssg/events',{timeout:30000});
  row=checked(await service.from('rmc_events').select('id,data').eq('id',row.id).single());
  assert.equal(row.data.endDate,date(5)); assert.equal(row.data.attendanceWindows.length,2);
  await page.goto(`${base}/#/ssg/events/create?kind=flag_ceremony`,{waitUntil:'networkidle0'});
  await page.waitForSelector('#event-title');
  await choose('Activity type','Merit activity');
  assert.equal(await page.$eval('main h1',el=>el.textContent),'Create Merit Activity');
  await setInput('#event-title',title); await setInput('#event-details','Browser merit verification');
  await setInput('#event-start-date',date(1)); await setInput('#event-end-date',date(1));
  await setInput('input[id^="time-in-"]','08:00'); await setInput('input[id^="time-out-"]','10:00');
  await clickText('Schedule Merit Activity');
  await page.waitForFunction(()=>location.hash==='#/ssg/events',{timeout:30000});
  const rows=checked(await service.from('rmc_events').select('data').eq('data->>title',title));
  assert.equal(rows.length,2); assert.equal(rows.find(r=>r.data.kind==='merit').data.meritHours,1);
  assert.deepEqual(errors,[]);
  console.log('PASS: flag-retreat standard, activity switching, service multi-window save, mobile layout, date extension, and fixed merit creation.');
} finally {
  const rows=checked(await service.from('rmc_events').select('id').eq('data->>title',title));
  if(rows.length) checked(await service.from('rmc_events').delete().in('id',rows.map(r=>r.id)));
  await browser.close();
}
