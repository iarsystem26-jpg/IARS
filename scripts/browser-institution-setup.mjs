import fs from 'node:fs';
import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const base = process.env.AUDIT_BASE_URL || 'http://localhost:3000';
const account = JSON.parse(fs.readFileSync('.demo-accounts.local','utf8')).find(a => a.role === 'admin');
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const page = await browser.newPage(); const errors = [];
page.on('pageerror', error => errors.push(error.message));
fs.mkdirSync('artifacts/institutions', { recursive: true });
try {
  await page.setViewport({ width: 1440, height: 1100 });
  await page.goto(`${base}/#/login`, { waitUntil: 'networkidle0' });
  await page.waitForSelector('#landing-login-identifier');
  await page.type('#landing-login-identifier', account.username);
  await page.type('#landing-login-password', account.password);
  await page.$eval('#landing-login-password', input => input.closest('form').requestSubmit());
  await page.waitForFunction(() => !document.querySelector('#landing-login-identifier'), { timeout: 45000 });
  await page.goto(`${base}/#/ssg/panel`, { waitUntil: 'networkidle0' });
  const clickText = async (selector, text) => page.evaluate((selector, text) => { const button = [...document.querySelectorAll(selector)].find(e => e.textContent.trim() === text); if (!button) throw Error(`Missing control: ${text}`); button.click(); }, selector, text);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(e => e.textContent.trim() === 'Add institution'));
  await clickText('button', 'Add institution');
  await page.waitForSelector('main[aria-label="Institution setup"]');
  assert.equal(await page.$('[role="dialog"]'), null, 'Setup must be a page');
  assert.ok(page.url().includes('/admin/institutions/new'));
  const fill = async (label, value) => {
    const input = await page.evaluateHandle(label => [...document.querySelectorAll('form label')].find(el => el.firstChild?.textContent === label)?.querySelector('input'), label);
    await input.asElement().evaluate((el, value) => { const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; setter.call(el, value); el.dispatchEvent(new Event('input', { bubbles: true })); }, value);
    assert.equal(await input.asElement().evaluate(el => el.value), value, `Entering ${label}`);
  };
  await clickText('form button', 'Continue');
  assert.ok(await page.$('form input[type="email"]'), 'Required details must block progress');
  for (const [label, value] of [['Institution name', 'North Academy'], ['Short name', 'NA'], ['Institution ID', 'north-academy'], ['Registered legal name', 'North Academy Inc.'], ['Institution address', 'Davao City'], ['Support email', 'support@example.com'], ['Privacy contact email', 'privacy@example.com']]) await fill(label, value);
  await clickText('form button', 'Continue');
  await page.waitForFunction(() => document.querySelector('form')?.innerText.includes('Administrator password'));
  const generated = await page.$eval('input[autocomplete="new-password"]', input => input.value);
  assert.ok(generated.length >= 12, 'Password is automatically generated');
  for (const [label, value] of [['Administrator name', 'School Owner'], ['Administrator email', 'owner@example.com'], ['Administrator username', 'school.owner']]) await fill(label, value);
  const password = await page.$('input[autocomplete="new-password"]');
  await password.evaluate(el => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, 'weakpassword'); el.dispatchEvent(new Event('input', { bubbles: true })); });
  await clickText('form button', 'Continue');
  assert.ok(await page.$('input[autocomplete="new-password"]'), 'Weak password must block progress');
  await clickText('form button', 'Generate');
  await clickText('form button', 'Continue');
  await page.waitForSelector('input[type="file"]');
  const uploader = await page.$('input[type="file"]'); await uploader.uploadFile('public/iars-icon.png');
  await page.waitForFunction(() => document.querySelector('form')?.innerText.includes('Suggested from logo'));
  assert.equal(await page.$('form select'), null, 'Existing custom dropdowns must be used');
  await clickText('form button', 'Suggested from logo');
  await clickText('[role="option"]', 'Custom colors');
  await page.waitForSelector('input[type="color"]');
  await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.querySelector('main h2'));
  const frame = page.frames().find(frame => frame.url() === 'about:srcdoc');
  assert.ok(frame, 'Preview must render in an isolated document');
  const light = await frame.evaluate(() => ({ dark: document.documentElement.classList.contains('dark'), background: getComputedStyle(document.querySelector('main').parentElement.parentElement).backgroundColor, primary: document.documentElement.style.getPropertyValue('--palette-brand-500') }));
  assert.equal(light.dark, false); assert.ok(light.primary);
  await page.evaluate(() => document.querySelectorAll('[data-toast-root] button[aria-label^="Dismiss"]').forEach(button => button.click()));
  await page.screenshot({ path: 'artifacts/institutions/setup-light.png', fullPage: true });
  await clickText('button', 'dark');
  await frame.waitForFunction(() => document.documentElement.classList.contains('dark'));
  const contrast = await frame.evaluate(() => {
    const luminance = value => value.match(/[\d.]+/g).slice(0,3).map(Number).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0);
    return [...document.querySelectorAll('.app-button')].map(button=>{const style=getComputedStyle(button);const values=[luminance(style.color),luminance(style.backgroundColor)].sort((a,b)=>b-a);return(values[0]+.05)/(values[1]+.05);});
  });
  assert.ok(contrast.every(ratio => ratio >= 4.5), 'Preview action labels must have readable contrast');
  await page.screenshot({ path: 'artifacts/institutions/setup-dark.png', fullPage: true });
  const frameClick = async text => frame.evaluate(text => { const button = [...document.querySelectorAll('button')].find(el => el.textContent.trim() === text); if (!button) throw Error(`Missing preview control: ${text}`); button.click(); }, text);
  await frameClick('Show QR');
  await frame.waitForSelector('svg');
  const qrBefore = await frame.$eval('svg', svg => svg.innerHTML);
  await frameClick('Refresh QR');
  await frame.waitForFunction(before => document.querySelector('svg')?.innerHTML !== before, {}, qrBefore);
  await page.screenshot({ path: 'artifacts/institutions/setup-qr.png', fullPage: true });
  await frameClick('My records');
  await frame.waitForFunction(() => document.body.innerText.includes('Recent attendance'));
  await frameClick('Events');
  await frame.waitForFunction(() => document.body.innerText.includes('Upcoming events'));
  await clickText('form button', 'Continue');
  await page.waitForFunction(() => document.querySelector('form')?.innerText.includes('Create institution'));
  assert.equal(await page.$('input[autocomplete="new-password"]'), null, 'Review must not expose the password');
  await page.setViewport({ width: 390, height: 844 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.app-sidebar-layout')).paddingLeft === '0px');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'artifacts/institutions/setup-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile view must not overflow horizontally');
  await clickText('button', 'Back to institutions');
  await page.goto(`${base}/?institution=unknown-institution-verification#/login`, { waitUntil: 'networkidle0' });
  await page.waitForFunction(() => document.body.innerText.includes('Unable to open institution'));
  assert.equal(await page.$('#landing-login-identifier'), null, 'Unknown institution must not expose hub login');
  assert.deepEqual(errors, []);
  console.log('PASS: full-page wizard, required fields, generated/manual password checks, custom dropdowns, logo upload, interactive QR, preview navigation, light/dark, mobile layout, unknown institution rejection. No project request was submitted.');
} catch (error) { await page.screenshot({ path: 'artifacts/institutions/setup-failure.png', fullPage: true }); console.error(await page.evaluate(() => ({ url: location.hash, invalid: [...document.querySelectorAll('form input')].filter(input => !input.validity.valid).map(input => ({ label: input.closest('label')?.firstChild?.textContent, reason: input.validationMessage })), alerts: [...document.querySelectorAll('[role=alert]')].map(el => el.textContent) }))); throw error; } finally { await browser.close(); }

